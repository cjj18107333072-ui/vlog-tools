# 一个视频的"档案" = 字典（带标签的盒子）

# 【字典】：{} 装起来的，每个东西都有"标签: 值"
# 标签叫 key，值叫 value —— 左边是标签，右边是值
video = {
    "标题": "食堂隐藏美食",
    "播放量": 15800,
    "点赞": 2100,
    "评论": 156,
    "涨粉": 320,

}

# 用【标签】把值取出来
print("标题：", video["标题"])
print("播放量：", video["播放量"])
print("点赞：", video["点赞"])
print("评论：", video["评论"])
print("涨粉：", video["涨粉"])
