# 找出播放量最高的视频

# 【字典的列表】：[] 里装着 3 个 {}，每个 {} 是一个视频的档案
videos = [
    {"标题": "食堂隐藏美食", "播放量": 15800, "点赞": 2100, "涨粉": 320},
    {"标题": "大二的一天",   "播放量": 3200,  "点赞": 480,  "涨粉": 45},
    {"标题": "宿舍改造",     "播放量": 20000,  "点赞": 1300, "涨粉": 180},
]

# 先假装"第 0 个视频"是冠军（best = 冠军）
# videos[0] 就是列表里第一个字典（[]里的下标从 0 开始数）
best = videos[0]

# 【for 循环】：每个视频都来挑战一下冠军
for video in videos:
    # 【if】：如果"当前视频"的播放量 > "冠军"的播放量
    if video["播放量"] > best["播放量"]:
        best = video   # 冠军换人！让位给播放量更高的

# 循环结束，best 就是播放量最高的那个
print(f"你的爆款是《{best['标题']}》，播放量 {best['播放量']}")
