# 帮你判断 Vlog 标题好不好的小工具

# 【列表】：一排标题，用 [] 装起来，像一个清单
titles = [
    "大二的一天",
    "图书馆学习打卡",
    "食堂隐藏美食",
    "宿舍改造",
    "第一次兼职体验",
]

# 【for 循环】：把列表里的标题，一个个拿出来（每次都装进变量 t）
for t in titles:
    # 【if/else】：判断标题长度够不够吸引人（len 是"数长度"）
    if len(t) >= 8:
        print(f"✅ {t}  →  标题够长，可以发")
    else:
        print(f"⚠️  {t}  →  太短，建议补细节")
