# 找出播放量最高的视频，并打印它的详细信息
# ⚠️ 注意：这个代码里藏了一个错，别改它，先直接跑，看会发生什么

videos = [
    {"标题": "食堂隐藏美食", "播放量": 15800, "点赞": 2100, "涨粉": 320},
    {"标题": "大二的一天",   "播放量": 3200,  "点赞": 480,  "涨粉": 45},
    {"标题": "宿舍改造",     "播放量": 8600,  "点赞": 1300, "涨粉": 180},
]

best = videos[0]
for video in videos:
    if video["播放量"] > best["播放量"]:
        best = video

# 打印爆款的详细信息
print(f"你的爆款是《{best['标题']}》")
print(f"播放量：{best['播放量']}")
print(f"点赞：{best['点赞']}")
print(f"涨粉：{best['涨粉']}")
